/**
 * Issue #154 Phase 2-C2.6-B2-C2A-R2: the task B2-C2A-R1 still left unmeasured, measured again with a 60-minute budget.
 * Research only. Never import from Production.
 *
 * B2-C2A searched 320 P1 top-16 reservation contexts (20 Targets x 16 ranks) and left 2 tasks unmeasured (10-minute
 * timeout). R1 searched those 2 again with a 30-minute budget: 1 completed, 1 timed out again, so R1 ended
 * `B2C2AR1_INCOMPLETE` with 319 / 320 measured. R2 changes nothing about the Search, the context, the capture or the
 * population; it runs only the R1 retry tasks R1 left unmeasured (timeout), once more, with a 60-minute budget:
 *
 * ```text
 * retry manifest (taskIds = R1 RESULT retry rows with process = timeout, record = null; made before the run)
 * Export + Target manifest (the unchanged B2-C2A manifest, regenerated by the existing prepare path)
 *   -> B2-C2A tasks child: derivePhase2C26B2C1Schedule() -> buildPhase2C26B2C2ATasks()   (20 x 16 = 320 tasks)
 *   -> selectPhase2C26B2C2AR2Tasks(): the retry taskIds only, each exactly once
 *   -> B2-C2A search child per task: runPhase2C26B2C2ATask() -> runPhase2C26B2C2ASearch() -> visitPlannerAlternativeCandidates()
 *      (default extent, 4 operation-cost cohorts drained, 5th cost sentinel, safety cap 1024, heap 8192 MB: all unchanged)
 * ```
 *
 * This module is the Search side of R2: it never reads the B2-C2A RESULT, the R1 RESULT, the oracle RESULT, the oracle
 * manifest or any compatibility / first-compatible / exact information. The retry manifest it parses holds task IDs and
 * source hashes only. Only the post-hoc analyzer reads the RESULTs and the oracle, after every retry task ended.
 */
