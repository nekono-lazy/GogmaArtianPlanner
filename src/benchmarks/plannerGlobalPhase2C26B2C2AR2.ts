// ---------------------------------------------------------------- the retry manifest (a Search input)

/**
 * The tasks to measure again. It is produced before the run from the R1 RESULT retry rows R1 did not measure because their
 * child timed out, and holds task IDs and source hashes only: no compatibility, oracle field, Candidate key, rank of an
 * exact Candidate, expected Candidate count or expected result.
 */
export interface Phase2C26B2C2AR2RetryManifest {
  phase: string
  sourceR1ResultSha256: string
  sourceR1RetryManifestSha256: string
  sourceB2C2AResultSha256: string
  sourceTargetManifestSha256: string
  /** The Export B2-C2A and R1 measured (from the R1 RESULT's provenance). */
  exportSha256: string
  taskIds: string[]
}

const RETRY_MANIFEST_KEYS = ['exportSha256', 'phase', 'sourceB2C2AResultSha256', 'sourceR1ResultSha256', 'sourceR1RetryManifestSha256', 'sourceTargetManifestSha256', 'taskIds']

/**
 * Reads a retry manifest as untrusted JSON: exactly the manifest keys (nothing else may ride along), the registered R1
 * RESULT / R1 retry manifest / B2-C2A RESULT / Target manifest, a SHA-256 Export, and exactly one distinct B2-C2A task ID.
 */
export function parsePhase2C26B2C2AR2RetryManifest(json: unknown): { valid: boolean; issues: string[]; manifest: Phase2C26B2C2AR2RetryManifest | null } {
  const issues: string[] = []
  if (!isObject(json)) return { valid: false, issues: ['the retry manifest is not an object'], manifest: null }
  if (!same(Object.keys(json).sort(), RETRY_MANIFEST_KEYS)) issues.push(`the retry manifest keys are not exactly ${RETRY_MANIFEST_KEYS.join(', ')}`)
  if (json.sourceR1ResultSha256 !== PHASE2C26B2C2AR2_SOURCE.r1ResultSha256) issues.push('sourceR1ResultSha256 is not the registered R1 RESULT')
  if (json.sourceR1RetryManifestSha256 !== PHASE2C26B2C2AR2_SOURCE.r1RetryManifestSha256) issues.push('sourceR1RetryManifestSha256 is not the registered R1 retry manifest')
  if (json.sourceB2C2AResultSha256 !== PHASE2C26B2C2AR2_SOURCE.b2c2aResultSha256) issues.push('sourceB2C2AResultSha256 is not the registered B2-C2A RESULT')
  if (json.sourceTargetManifestSha256 !== PHASE2C26B2C2AR2_SOURCE.targetManifestSha256) issues.push('sourceTargetManifestSha256 is not the registered B2-C2A Target manifest')
  if (typeof json.exportSha256 !== 'string' || !SHA256.test(json.exportSha256)) issues.push('exportSha256 is not a SHA-256')
  if (typeof json.phase !== 'string') issues.push('phase is not a string')
  const ids = Array.isArray(json.taskIds) ? json.taskIds : null
  if (!ids || !ids.every(id => typeof id === 'string' && TASK_ID.test(id))) issues.push('taskIds is not a list of B2-C2A task IDs')
  else {
    if (ids.length !== PHASE2C26B2C2AR2_EXPECTED_RETRY_TASKS) issues.push(`taskIds holds ${ids.length} tasks, not ${PHASE2C26B2C2AR2_EXPECTED_RETRY_TASKS}`)
    if (new Set(ids).size !== ids.length) issues.push('taskIds repeats a task')
    if (!same(ids, [...ids].sort(compare))) issues.push('taskIds is not in ascending order')
  }
  if (issues.length > 0) return { valid: false, issues, manifest: null }
  return { valid: true, issues: [], manifest: { phase: String(json.phase), sourceR1ResultSha256: String(json.sourceR1ResultSha256),
    sourceR1RetryManifestSha256: String(json.sourceR1RetryManifestSha256), sourceB2C2AResultSha256: String(json.sourceB2C2AResultSha256),
    sourceTargetManifestSha256: String(json.sourceTargetManifestSha256), exportSha256: String(json.exportSha256), taskIds: (ids as string[]).map(String) } }
}

// ---------------------------------------------------------------- retry task selection

export interface Phase2C26B2C2AR2Selection {
  valid: boolean
  issues: string[]
  /** The selected tasks, unchanged from the reconstruction, in retry manifest order. */
  tasks: Phase2C26B2C2ATaskInput[]
}

/**
 * The retry tasks out of the full reconstruction: the construction must be valid and hold exactly 20 x 16 tasks with
 * unique IDs, and every retry ID must name exactly one of them. The tasks are returned exactly as reconstructed (the same
 * task the B2-C2A Search child received), never rebuilt or patched.
 */
export function selectPhase2C26B2C2AR2Tasks(construction: Pick<Phase2C26B2C2ATaskConstruction, 'valid' | 'issues' | 'tasks'>, taskIds: readonly string[]): Phase2C26B2C2AR2Selection {
  const issues: string[] = []
  if (!construction.valid) issues.push(`the task reconstruction is not valid: ${construction.issues.join('; ')}`)
  if (construction.tasks.length !== PHASE2C26B2C2A_EXPECTED_TASKS) issues.push(`the reconstruction holds ${construction.tasks.length} tasks, not ${PHASE2C26B2C2A_EXPECTED_TASKS}`)
  if (new Set(construction.tasks.map(t => t.taskId)).size !== construction.tasks.length) issues.push('the reconstruction repeats a task ID')
  if (taskIds.length !== PHASE2C26B2C2AR2_EXPECTED_RETRY_TASKS) issues.push(`${taskIds.length} retry tasks, not ${PHASE2C26B2C2AR2_EXPECTED_RETRY_TASKS}`)
  if (new Set(taskIds).size !== taskIds.length) issues.push('a retry task repeats')
  const tasks: Phase2C26B2C2ATaskInput[] = []
  for (const id of taskIds) {
    const matches = construction.tasks.filter(t => t.taskId === id)
    if (matches.length !== 1) { issues.push(`${id}: ${matches.length} reconstructed tasks`); continue }
    tasks.push(structuredClone(matches[0]!))
  }
  return { valid: issues.length === 0, issues, tasks: issues.length === 0 ? tasks : [] }
}
