/**
 * Issue #154 Phase 2-C2.6-B2-C2A-R1: the B2-C2A timeout subset, measured again with a longer budget. Research only. Never
 * import from Production.
 *
 * B2-C2A searched the P1 top-16 reservation contexts of its 20 validation Targets (320 tasks) and ended
 * `B2C2A_INCOMPLETE` because tasks that hit the 10-minute Stage 1 budget were never measured. R1 changes nothing about
 * the Search, the context, the capture or the population; it only runs the tasks B2-C2A left unmeasured once more, with a
 * longer budget and one task at a time:
 *
 * ```text
 * retry manifest (taskIds = B2-C2A RESULT rows with process = timeout, record = null; made before the run)
 * Export + Target manifest (the unchanged B2-C2A manifest, regenerated by the existing prepare path)
 *   -> B2-C2A tasks child: derivePhase2C26B2C1Schedule() -> buildPhase2C26B2C2ATasks()   (20 x 16 = 320 tasks)
 *   -> selectPhase2C26B2C2AR1Tasks(): the retry taskIds only, each exactly once
 *   -> B2-C2A search child per task: runPhase2C26B2C2ATask() -> runPhase2C26B2C2ASearch() -> visitPlannerAlternativeCandidates()
 *      (default extent, 4 operation-cost cohorts drained, 5th cost sentinel, safety cap 1024: all unchanged)
 * ```
 *
 * This module is the Search side of R1: it never reads the B2-C2A RESULT, the oracle RESULT, the oracle manifest or any
 * compatibility / first-compatible / exact information. The retry manifest it parses holds task IDs and source hashes
 * only. Only the post-hoc analyzer reads the RESULT and the oracle, after every retry task ended.
 */
import { stableStringify } from '../domain/models/hashing'
import {
  PHASE2C26B2C2A_CANDIDATE_SAFETY_CAP,
  PHASE2C26B2C2A_EXPECTED_TASKS,
  PHASE2C26B2C2A_MAX_COST_COHORTS,
  PHASE2C26B2C2A_STAGE1,
  type Phase2C26B2C2ATaskConstruction,
  type Phase2C26B2C2ATaskInput,
} from './plannerGlobalPhase2C26B2C2A'

type Json = Record<string, unknown>
const isObject = (value: unknown): value is Json => typeof value === 'object' && value !== null && !Array.isArray(value)
const same = (a: unknown, b: unknown) => {
  try { return stableStringify(a ?? null) === stableStringify(b ?? null) } catch { return false }
}
const compare = (a: string, b: string) => a < b ? -1 : a > b ? 1 : 0
const SHA256 = /^[0-9a-f]{64}$/
/** A B2-C2A task ID (`buildPhase2C26B2C2ATasks()`): manifest Target index and P1 rank, both two digits. */
const TASK_ID = /^t\d{2}-r\d{2}$/

// ---------------------------------------------------------------- registered before the formal retry

